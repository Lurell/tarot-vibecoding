import fs from 'fs';
import path from 'path';

const CARDS_DIR = path.resolve('public/cards');
const OUTPUT = path.resolve('src/data/card-images.ts');

// Priority: png > webp > jpg > svg
const extPriority = ['.png', '.webp', '.jpg', '.jpeg', '.svg'];

const allFiles = fs.readdirSync(CARDS_DIR);

// Group by base name, pick the best format for each card
const byBasename = new Map();
for (const file of allFiles) {
  const ext = path.extname(file).toLowerCase();
  if (!extPriority.includes(ext)) continue;
  const base = path.basename(file, ext);
  const existing = byBasename.get(base);
  if (!existing || extPriority.indexOf(ext) < extPriority.indexOf(existing.ext)) {
    byBasename.set(base, { file, ext });
  }
}

// Build data URIs
const entries = [];
for (const [base, { file, ext }] of byBasename) {
  const filePath = path.join(CARDS_DIR, file);
  const buf = fs.readFileSync(filePath);

  let dataUri;
  if (ext === '.svg') {
    const content = buf.toString('utf-8');
    dataUri = `data:image/svg+xml,${encodeURIComponent(content)}`;
  } else {
    const mimeMap = { '.png': 'image/png', '.webp': 'image/webp', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg' };
    const b64 = buf.toString('base64');
    dataUri = `data:${mimeMap[ext]};base64,${b64}`;
  }
  entries.push({ file, dataUri, base });
}

// Sort for stable output
entries.sort((a, b) => a.file.localeCompare(b.file));

const output = `// Auto-generated by scripts/generate-card-images.mjs
// Do not edit manually

const cardImages: Record<string, string> = {
${entries.map(e => `  '${e.file}': '${e.dataUri}'`).join(',\n')}
};

export function getCardImageDataUri(imageFile: string): string {
  return cardImages[imageFile] || cardImages['card-back.svg']
    || cardImages['card-back.png'] || cardImages['card-back.webp'] || '';
}

export function getCardBackDataUri(): string {
  return cardImages['card-back.svg'] || cardImages['card-back.png'] || cardImages['card-back.webp'] || '';
}
`;

fs.writeFileSync(OUTPUT, output);

const sizes = entries.map(e => `${e.file} (${(new TextEncoder().encode(e.dataUri).length / 1024).toFixed(1)}KB)`);
console.log(`Generated ${OUTPUT} with ${entries.length} card images`);
console.log(`Total data URI size: ~${(new TextEncoder().encode(output).length / 1024).toFixed(0)}KB`);
console.log(`\nCards: ${sizes.slice(0,5).join(', ')}${sizes.length > 5 ? '...' : ''}`);
